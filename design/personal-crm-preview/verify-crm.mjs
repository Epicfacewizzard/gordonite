  await page.locator('[data-view="reconnect"]').click();
  assert.equal(await page.locator('.crm-person').count(), 2);
  await page.locator('[data-view="all"]').click();
  await page.locator('[data-group="School"]').click();
  assert.equal(await page.locator('.crm-person').count(), 1);
  await page.locator('[data-group="All"]').click();
  await page.locator('#search').fill('ceramics');
  assert.equal(await page.locator('.crm-person').count(), 1);
  await page.locator('#search').fill('');
  const lastContact = await page.locator('.crm-facts dd').first().innerText();
  await page.getByRole('button', { name: 'Mark done', exact: true }).click();
  assert.equal(await page.locator('#followup-count').innerText(), '1');
  assert.equal(await page.locator('.crm-facts dd').first().innerText(), lastContact);
  await page.getByRole('button', { name: 'Log a conversation', exact: true }).click();
  await page.getByLabel('What did you talk about?', { exact: true }).fill('A new trail and the first pottery class.');
  await page.getByLabel('Next follow-up (optional)', { exact: true }).fill('Ask about the mug');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.match(await page.locator('#form-error').innerText(), /both/);
  await page.getByLabel('Follow-up date', { exact: true }).fill('2026-10-20');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal(await page.locator('.crm-timeline li').count(), 3);
  assert.match(await page.locator('.crm-facts dd').first().innerText(), /Oct 15, 2026/);
  await page.reload();
  assert.equal(await page.locator('.crm-timeline li').count(), 3);
  await page.getByRole('button', { name: 'Edit note', exact: true }).click();
  await page.getByLabel('Person note', { exact: true }).fill('Remember to ask about <pottery>.');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal(await page.locator('.crm-note').innerText(), 'Remember to ask about <pottery>.');
  await page.getByRole('button', { name: 'New person', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('<New friend>');
  await page.getByLabel('How you know each other', { exact: true }).fill('Book club');
  await page.getByLabel('Birthday (MM-DD, optional)', { exact: true }).fill('02-30');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.match(await page.locator('#form-error').innerText(), /real birthday/);
  await page.getByLabel('Birthday (MM-DD, optional)', { exact: true }).fill('02-29');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal(await page.locator('#people-count').innerText(), '7');
  assert.equal(await page.locator('#profile h2').innerText(), '<New friend>');
  await page.getByText('About this concept & backup', { exact: true }).click();
  await page.getByRole('button', { name: 'Show backup', exact: true }).click();
  const backup = await page.locator('#backup-text').inputValue();
  assert.equal(JSON.parse(backup).people.length, 7);
  await page.locator('#restore-text').fill('{"format":1,"people":[{}]}');
  await page.getByRole('button', { name: 'Restore backup', exact: true }).click();
  assert.equal(await page.locator('#people-count').innerText(), '7');
  await page.locator('#restore-text').fill(backup);
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Restore backup', exact: true }).click();
  assert.equal(await page.locator('#people-count').innerText(), '7');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Reset fictional demo', exact: true }).click();
